@dataclass(frozen=True)
class FieldSpec:
    """One register field: its stable key, the team's word for it, and what it is."""

    key: str
    label: str
    group: Group
    # The origin a value of this field can have. Where a field can be stated by
    # the source *or* inferred, this is the weaker of the two and the display
    # layer states which one actually applied.
    provenance: Provenance
    # Shown above the fold. Everything else folds into "More details".
    prominent: bool = False
    # One sentence for a colleague, where the label alone would mislead.
    note: str | None = None
    # True when nothing in a source API can fill this field, so it can only ever
    # arrive from reading a document. These are the keys a stored extraction may
    # use, and the only ones; see FIELDS_EXTRACTED.
    extracted: bool = False


