BY_KEY: dict[str, FieldSpec] = {spec.key: spec for spec in FIELDS}

# The keys a stored extraction may use. Pinning this list is what closes
# docs/decisions/0001: a field renamed in a prompt is now an error on the way in
# rather than a blank on the page that looks like "the notice did not say".
FIELDS_EXTRACTED: tuple[str, ...] = tuple(spec.key for spec in FIELDS if spec.extracted)


def label(key: str) -> str:
    """The team's word for a field. Falls back to the key rather than inventing one."""
    spec = BY_KEY.get(key)
    return spec.label if spec is not None else key


def spec(key: str) -> FieldSpec | None:
    return BY_KEY.get(key)


def in_group(group: Group) -> tuple[FieldSpec, ...]:
    """Every field of one group, in workbook order."""
    return tuple(item for item in FIELDS if item.group is group)


def provenance_label(origin: Provenance) -> str:
    return PROVENANCE_LABELS[origin]


def group_label(group: Group) -> str:
    return GROUP_LABELS[group]
